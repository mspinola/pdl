"""The analysis reports as pages: analysis/index.html and analysis/<report>.html.

The reports are generated Markdown in docs/ (src/transactions_analysis.py and
the rest), so the site converts them at build time rather than keeping a second
copy. The converter handles what those reports use: headings, paragraphs,
lists, tables, and inline code, bold, italics and links.
"""
import html, os, re

import league_data as d
from frame import E, page, slug

REPORTS = [
    ("transactions", "Who works the waiver wire", "Claims, free agent pickups, timing, streaming, and the points pickups scored, since 2000."),
    ("lineups-and-luck", "Lineup decisions and schedule luck", "Points left on the bench, games lost to the lineup, and luck against an all-play record."),
    ("got-away", "The ones that got away", "Players dropped who went on to start for someone else."),
    ("draft-value", "Draft value", "What each pick gave the team that made it, by round, slot and owner, since 2008."),
]


def inline(text, teams):
    t = E(text)
    t = re.sub(r"`([^`]+)`", r"<code>\1</code>", t)
    t = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", t)
    t = re.sub(r"(?<![\w*])\*([^*]+)\*(?![\w*])", r"<em>\1</em>", t)
    t = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r"<a href='\2'>\1</a>", t)
    return t


def convert(md, teams):
    out, para, lines = [], [], md.split("\n")

    def flush():
        if para:
            out.append(f"<p>{inline(' '.join(para), teams)}</p>")
            para.clear()
    i = 0
    while i < len(lines):
        line = lines[i]
        if not line.strip():
            flush()
        elif line.startswith("#"):
            flush()
            level = len(line) - len(line.lstrip("#"))
            if level == 1:
                i += 1
                continue   # the page supplies its own title
            text = line.lstrip("#").strip()
            out.append(f"<h{level} id='{slug(text)}'>{inline(text, teams)}</h{level}>")
        elif line.startswith("|"):
            flush()
            rows = []
            while i < len(lines) and lines[i].startswith("|"):
                rows.append([c.strip() for c in lines[i].strip().strip("|").split("|")])
                i += 1
            head, body = rows[0], [r for r in rows[1:] if not all(re.fullmatch(r":?-+:?", c) for c in r)]
            num_col = [all(re.fullmatch(r"[-+]?[\d.,]+%?|-|", r[j]) for r in body if j < len(r)) for j in range(len(head))]
            th = "".join(f"<th class='{'' if num_col[j] else 'l'}'>{inline(h, teams)}</th>" for j, h in enumerate(head))
            trs = "".join("<tr>" + "".join(f"<td class='{'' if num_col[j] else 'l'}'>{team_cell(c, teams)}</td>"
                                           for j, c in enumerate(r)) + "</tr>" for r in body)
            out.append(f"<div class='table-wrap'><table class='data'><thead><tr>{th}</tr></thead><tbody>{trs}</tbody></table></div>")
            continue
        elif re.match(r"\s*- ", line):
            flush()
            items = []
            while i < len(lines) and (re.match(r"\s*- ", lines[i]) or (lines[i].startswith("  ") and items)):
                if re.match(r"\s*- ", lines[i]):
                    items.append(lines[i].split("- ", 1)[1])
                else:
                    items[-1] += " " + lines[i].strip()
                i += 1
            out.append("<ul>" + "".join(f"<li>{inline(x, teams)}</li>" for x in items) + "</ul>")
            continue
        else:
            para.append(line.strip())
        i += 1
    flush()
    return "\n".join(out)


def team_cell(text, teams):
    """A table cell that is a team name links to the franchise page."""
    if text in teams:
        return f"<a href='../franchises/{slug(text)}.html'>{E(text)}</a>"
    return inline(text, teams)


def build(dist):
    os.makedirs(f"{dist}/analysis", exist_ok=True)
    teams = set(d.identities())
    base = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    for name, title, blurb in REPORTS:
        md = open(f"{base}/docs/{name}.md").read()
        # the reports' note on how they are made is for the repository, not the site
        md = re.sub(r"Generated by `[^`]+`[^.]*\.\s*", "", md)
        body = (f"<div class='season report'><h1>{E(title)}</h1><nav class='pn'><a href='index.html'>All analyses</a></nav>"
                f"{convert(md, teams)}</div>")
        with open(f"{dist}/analysis/{name}.html", "w") as f:
            f.write(page(f"{title}, PDL", body, description=blurb))
    items = "".join(f"<li><a href='{n}.html'>{E(t)}</a><span>{E(b)}</span></li>" for n, t, b in REPORTS)
    items += ("<li><a href='../trades/index.html'>Trades</a><span>Who trades, with whom, and every trade since 2000</span></li>"
              "<li><a href='../h2h/index.html'>Head to head</a><span>Every pairing's record and games</span></li>")
    body = ("<div class='home'><h1>Analysis</h1><p class='lede'>Studies of how the league is played, built from every "
            "game, lineup, transaction and pick in the archive. Owners appear by team, as everywhere on the site. "
            "Each report says how strong its findings are: what chance alone could produce is part of every "
            f"comparison.</p><ul class='doors'>{items}</ul></div>")
    with open(f"{dist}/analysis/index.html", "w") as f:
        f.write(page("PDL analysis", body, description="Analyses of the PDL's history."))
    return len(REPORTS) + 1
