"""The ones that got away: players dropped who started for someone else.

For every in-season drop from 2008 (transactions.json, MFL era, where lineups
exist), what the player did next: his starts and points for any other team for
the rest of that season and all of the next. A dynasty roster can keep a player
for years, so one season ahead is the horizon, and a re-acquisition by the team
that dropped him is noted.

The measure is value over an average starter: each start's points minus the
average starter's points at the player's position that season, in units of the
season's average start. A quarterback is set against quarterbacks, a tight end
against tight ends, and 2010 compares with 2020 across the 2018 scoring change.
A player only counts as one that got away if he beat a typical starter. Drops before that season's draft (the cut to retainments) are left out:
those are retention decisions, not waiver-wire ones.

    python3 src/got_away.py     # datasets/got_away.csv, docs/got-away.md
"""
import csv, json, os, statistics, sys
from collections import defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import weekly
from fetch_mfl import LAST_SEASON

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IN_SEASON = range(0, 18)   # weeks 0 (after the draft) to 17


def draft_starts():
    """Season -> timestamp of its first draft pick."""
    out = {}
    for y in range(2008, LAST_SEASON + 1):
        p = f"{BASE}/mfl_archive/{y}/draft_results.json"
        if not os.path.exists(p):
            continue
        picks = json.load(open(p)).get("draftResults", {}).get("draftUnit", {}).get("draftPick", [])
        picks = picks if isinstance(picks, list) else [picks]
        ts = [int(x["timestamp"]) for x in picks if x.get("timestamp")]
        if ts:
            out[y] = min(ts)
    return out


def main():
    rows = weekly.seasons()
    pos = weekly.positions()
    avg = weekly.starter_averages(rows)
    drafted = draft_starts()
    starts = defaultdict(list)   # player id -> [(season, week, team, score)]
    for r in rows:
        if r["stage"] == "consolation":
            continue
        for p in r["players"]:
            if p["started"]:
                starts[p["id"]].append((r["season"], r["week"], r["team"], p["score"]))
    moves = json.load(open(f"{BASE}/transactions.json"))
    import datetime as dt
    drops = [m for m in moves if m["source"] == "mfl" and m["action"] == "drop" and m["week"] in IN_SEASON
             and m["player_id"] and m["season"] in drafted
             and dt.datetime.fromisoformat(m["when"]).timestamp() > drafted[m["season"]]]
    readds = {(m["season"], m["team"], m["player_id"]) for m in moves if m["action"] == "add"}
    readds |= {(m["season"] + 1, m["team"], m["player_id"]) for m in moves if m["action"] == "add"}
    out = []
    for d in drops:
        s, w, team, pid = d["season"], d["week"], d["team"], d["player_id"]
        later = [(y, wk, t, sc) for y, wk, t, sc in starts.get(pid, [])
                 if t != team and ((y == s and wk >= w) or y == s + 1)]
        if not later:
            continue
        pts = sum(sc for *_, sc in later)
        p = pos.get(pid)
        equiv = sum(weekly.over_average(sc, y, p, avg) for y, *_, sc in later)
        teams = sorted({t for _, _, t, _ in later})
        out.append({"season": s, "week": w, "dropped_by": team, "player": d["player"], "position": d["position"],
                    "starts_elsewhere": len(later), "points_elsewhere": round(pts, 1),
                    "value_over_average": round(equiv, 1), "started_for": "; ".join(teams),
                    "this_season_starts": sum(1 for y, *_ in later if y == s),
                    "next_season_starts": sum(1 for y, *_ in later if y == s + 1),
                    "horizon_complete": s + 1 < LAST_SEASON,
                    "reacquired": (s, team, pid) in readds or (s + 1, team, pid) in readds})
    out.sort(key=lambda r: -r["value_over_average"])
    cols = list(out[0])
    with open(f"{BASE}/datasets/got_away.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(cols)
        w.writerows([[r[c] for c in cols] for r in out])
    report(out, drops)
    print(f"{len(drops):,} in-season drops from 2008, {len(out):,} of them started for another team within the horizon")
    print("wrote datasets/got_away.csv and docs/got-away.md")
    return 0


def report(out, drops):
    done = [r for r in out if r["horizon_complete"]]
    L = ["# The ones that got away", "",
         "Generated by `python3 src/got_away.py`. Every in-season drop from 2008, and what the player did next "
         "for other teams: the rest of that season and all of the next. Value is points above the "
         "average starter at the player's position that season, counted in that season's average starts, so "
         "positions and eras compare: 5 means five average starts' worth of points beyond a typical starter. Kickers and defenses are shown, though they are "
         "dropped and re-added as a matter of routine.", "",
         f"{len(drops):,} in-season drops. {len(out):,} of the dropped players started for another team within the "
         f"horizon, and {sum(1 for r in out if r['value_over_average'] >= 5):,} were worth 5 or more average starts "
         "above a typical starter at their position.", ""]
    skill = [r for r in out if r["position"] not in ("K", "Def")]
    L += ["## The biggest, players at skill positions", "",
          "| Season | Week | Dropped by | Player | Pos | Starts elsewhere | Value over average | Then started for | Re-acquired |",
          "|---|---|---|---|---|---|---|---|---|"]
    for r in skill[:25]:
        L.append(f"| {r['season']} | {r['week']} | {r['dropped_by']} | {r['player']} | {r['position']} | "
                 f"{r['starts_elsewhere']} | {r['value_over_average']:+} | {r['started_for'].replace('; ', ', ')} | "
                 f"{'yes' if r['reacquired'] else ''} |")
    per = defaultdict(lambda: {"drops": 0, "regrets": 0, "equiv": 0.0})
    for d in drops:
        per[d["dropped_by"] if "dropped_by" in d else d["team"]]["drops"] += 1
    for r in skill:
        p = per[r["dropped_by"]]
        p["equiv"] += max(0, r["value_over_average"])
        p["regrets"] += r["value_over_average"] >= 5
    L += ["", "## By owner", "",
          "In-season drops, how many skill players went on to be worth 5 or more average starts above a typical "
          "starter elsewhere, and the value given away in all (only players who beat a typical starter count). Owners who drop more have more chances to regret it, so the rate "
          "per 100 drops is the fairer comparison.", "",
          "| Owner | Drops | Big ones that got away | Per 100 drops | Value given away |", "|---|---|---|---|---|"]
    for team, p in sorted(per.items(), key=lambda kv: -kv[1]["equiv"]):
        L.append(f"| {team} | {p['drops']} | {p['regrets']} | {100 * p['regrets'] / p['drops']:.1f} | {p['equiv']:.0f} |")
    L += ["", "## Notes", "",
          "- From 2008, where MFL kept lineups. A drop's horizon is incomplete if the next season is not finished "
          "(the CSV marks it), and its numbers can still grow.",
          "- \"Started for\" counts starts in another team's lineup, regular season and playoffs.",
          "- A player can be dropped more than once in a season, by different teams. Each drop is its own row.", ""]
    with open(f"{BASE}/docs/got-away.md", "w") as f:
        f.write("\n".join(L))


if __name__ == "__main__":
    sys.exit(main())
