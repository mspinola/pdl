"""Check the rule-change ledger and write a readable view of it.

rules/ledger.json lists each adopted change since the 2006 rule book. This
checks that every section it names exists in rules/baseline.json, and that every
source it cites resolves to exactly one entry in rules/sources/, so the ledger
cannot drift from its evidence. It then writes docs/rulebook/ledger.md: the
changes by section, the open questions, and the entry fee by season.

    python3 src/rulebook_ledger.py
"""
import json, os, sys

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RULES = f"{BASE}/rules"
SOURCE_FILES = {"changes_html": "entries", "email": "entries", "message_board": "entries", "polls": "polls"}
STATUSES = {"adopted", "in practice", "one season", "open"}


def load(name):
    with open(f"{RULES}/{name}") as f:
        return json.load(f)


def sources():
    out = {}
    for name, key in SOURCE_FILES.items():
        out[name] = load(f"sources/{name}.json")[key]
    return out


def resolve(src, ref):
    """The one source entry a ledger citation names."""
    entries = src.get(ref["file"])
    if entries is None:
        return None, f"unknown source file {ref['file']}"
    hits = [e for e in entries
            if (e.get("meeting") or e.get("season")) == ref["meeting"]
            and ref["match"].lower() in (e.get("proposal", "") + " " + str(e.get("outcome", ""))).lower()]
    if len(hits) != 1:
        return None, f"{ref['file']} {ref['meeting']} '{ref['match']}' matches {len(hits)} entries"
    return hits[0], None


def cite(ref, entry):
    s = entry.get("source") or {}
    if ref["file"] == "email":
        return f"email {s.get('date', '')}, \"{s.get('subject', '')}\""
    if ref["file"] == "message_board":
        return f"message board {s.get('date', ref['meeting'])}" + (f", \"{s['title']}\"" if s.get("title") else "")
    if ref["file"] == "polls":
        tally = ", ".join(f"{k} {v}" for k, v in (entry.get("tally") or {}).items())
        return f"league poll {ref['meeting']}" + (f" ({tally})" if tally else "")
    return f"changes.html, {ref['meeting']} meeting"


def check(ledger, baseline, src):
    ids = {s["id"] for s in baseline["sections"]}
    problems, seen = [], set()
    for c in ledger["changes"]:
        if c["id"] in seen:
            problems.append(f"{c['id']}: duplicate id")
        seen.add(c["id"])
        if c["status"] not in STATUSES:
            problems.append(f"{c['id']}: status {c['status']!r}")
        for s in c["sections"]:
            if s not in ids:
                problems.append(f"{c['id']}: no section {s} in the baseline")
        if not c["sources"]:
            problems.append(f"{c['id']}: no source")
        for ref in c["sources"]:
            _, err = resolve(src, ref)
            if err:
                problems.append(f"{c['id']}: {err}")
        if c.get("superseded_by") and c["superseded_by"] not in {x["id"] for x in ledger["changes"]}:
            problems.append(f"{c['id']}: superseded by unknown {c['superseded_by']}")
        if "—" in c["change"] or ";" in c["change"]:
            problems.append(f"{c['id']}: em dash or semicolon in the text")
    order = [(c["meeting"], i) for i, c in enumerate(ledger["changes"])]
    if order != sorted(order):
        problems.append("changes are not in meeting order")
    return problems


def report(ledger, baseline, src):
    titles = {s["id"]: s["title"] for s in baseline["sections"]}
    by_section = {}
    for c in ledger["changes"]:
        for s in c["sections"]:
            by_section.setdefault(s, []).append(c)
    n = {k: sum(c["status"] == k for c in ledger["changes"]) for k in STATUSES}
    lines = ["# Rule changes since the 2006 rule book", "",
             "Generated by `python3 src/rulebook_ledger.py` from `rules/ledger.json`, which is",
             "checked against `rules/baseline.json` and the evidence in `rules/sources/`.",
             "Do not edit by hand.", "",
             f"{len(ledger['changes'])} changes: {n['adopted']} adopted, {n['in practice']} in practice "
             f"with no recorded vote, {n['one season']} for one season only, and {n['open']} the record "
             "does not settle.", ""]

    lines += ["## Open questions", "", "The record does not settle these. Each needs the league's answer "
              "before the rule book can state the rule.", ""]
    for c in ledger["changes"]:
        if c["status"] == "open":
            lines.append(f"- **{c['meeting']}, section {', '.join(c['sections'])}.** {c['change']}")
    lines += ["", "## Entry fee by season", "", "| Season | Fee |", "|---|---|",
              "| 2004, 2005 | $50 |", "| 2006 (the baseline) | $60, $10 of it for the website and draft food |"]
    for c in ledger["changes"]:
        if c.get("fee"):
            lines.append(f"| {c['effective']} | {c['fee']} |")
    lines += ["", "Seasons not listed kept the previous fee, as far as the record shows.", ""]

    lines += ["## By section", ""]
    for sid in sorted(by_section, key=lambda x: tuple(map(int, x.split(".")))):
        lines += [f"### {sid} {titles[sid]}", ""]
        for c in by_section[sid]:
            eff = f", from {c['effective']}" if c.get("effective") and c["effective"] != c["meeting"] else ""
            tag = "" if c["status"] == "adopted" else f" *({c['status']})*"
            sup = f" Superseded by `{c['superseded_by']}`." if c.get("superseded_by") else ""
            lines.append(f"- **{c['meeting']}{eff}**{tag}: {c['change']}{sup}")
            if c.get("evidence"):
                lines.append(f"  - Evidence: {c['evidence']}")
            refs = []
            for ref in c["sources"]:
                entry, _ = resolve(src, ref)
                refs.append(cite(ref, entry))
            joined = refs[0] if len(refs) == 1 else ", ".join(refs[:-1]) + " and " + refs[-1]
            lines.append(f"  - Sources: {joined}")
        lines.append("")
    untouched = [s["id"] for s in baseline["sections"] if s["id"] not in by_section and s["level"] == 2]
    lines += ["## Sections no change touches", "",
              "These stand as written in 2006, as far as the record shows: " + ", ".join(untouched) + ".", ""]
    return "\n".join(lines)


def main():
    ledger, baseline, src = load("ledger.json"), load("baseline.json"), sources()
    problems = check(ledger, baseline, src)
    for p in problems:
        print("  PROBLEM", p)
    if problems:
        print(f"check: {len(problems)} problems")
        return 1
    out = f"{BASE}/docs/rulebook/ledger.md"
    with open(out, "w") as f:
        f.write(report(ledger, baseline, src) + "\n")
    print(f"check: {len(ledger['changes'])} changes, every section and source resolves")
    print(f"wrote {os.path.relpath(out, BASE)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
